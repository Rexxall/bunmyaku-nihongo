function pickUiLang() {
  const ok = x => UI_LANGS.includes(x) ? x : null;
  const fromTag = tag => ok(String(tag || '').toLowerCase().split('-')[0]);
  let saved = null; try { saved = JSON.parse(localStorage.getItem('bunmyaku:ui-lang')); } catch {}
  const hash = new URLSearchParams(location.hash.replace(/^#/, '')).get('lang');
  const pack = (() => { try { return JSON.parse(document.getElementById('pack-data').textContent).ui_language; } catch { return null; } })();
  return ok(hash) || ok(saved) || ok(pack) || (navigator.languages || [navigator.language]).map(fromTag).find(Boolean) || 'en';
}
const UI_LANG = pickUiLang();
const UI_INDEX = UI_LANGS.indexOf(UI_LANG);
function t(key, vars = {}) {
  const entry = STRINGS[key];
  if (!entry) return key;
  const value = entry[UI_INDEX] ?? entry[0];
  return typeof value === 'string' ? value.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : value;
}
// Static markup: data-i18n sets the text, data-i18n-label/-title/-placeholder set those attributes.
function applyStaticText(root = document) {
  document.documentElement.lang = UI_HTML_LANG[UI_LANG];
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const [data, attr] of [['i18nLabel', 'aria-label'], ['i18nTitle', 'title'], ['i18nPlaceholder', 'placeholder']]) {
    root.querySelectorAll(`[data-${data.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}]`).forEach(el => el.setAttribute(attr, t(el.dataset[data])));
  }
}
